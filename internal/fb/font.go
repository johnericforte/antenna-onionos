// glyphs maps a rune to one bitmask per row; bit 4 is the leftmost pixel.
var glyphs = map[rune][glyphHeight]uint8{}

func init() {
	for r, art := range glyphArt {
		var mask [glyphHeight]uint8
		for y, row := range strings.Split(art, "/") {
			if y >= glyphHeight {
				break
			}
			var bits uint8
			for x := 0; x < glyphWidth && x < len(row); x++ {
				if row[x] == '#' {
					bits |= 1 << (glyphWidth - 1 - x)
				}
			}
			mask[y] = bits
		}
		glyphs[r] = mask
	}
}

// TextWidth returns the pixel width of s at the given scale.
func TextWidth(s string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len([]rune(s)) * CellWidth * scale
}

// DrawText renders s with its top-left corner at x, y. Unknown runes render as
// a space. Scale multiplies each pixel into a square block.
func (f *Framebuffer) DrawText(x, y int, s string, scale int, c Color) {
	if scale < 1 {
		scale = 1
	}
	cursor := x
	for _, r := range s {
		mask, ok := glyphs[r]
		if !ok {
			cursor += CellWidth * scale
			continue
		}
		for row := 0; row < glyphHeight; row++ {
			bits := mask[row]
			if bits == 0 {
				continue
			}
			for col := 0; col < glyphWidth; col++ {
				if bits&(1<<(glyphWidth-1-col)) == 0 {
					continue
				}
				if scale == 1 {
					f.SetPixel(cursor+col, y+row, c)
				} else {
					f.Rect(cursor+col*scale, y+row*scale, scale, scale, c)
				}
			}
		}
		cursor += CellWidth * scale
	}
}

// DrawTextCentered renders s horizontally centered within the panel width.
func (f *Framebuffer) DrawTextCentered(y int, s string, scale int, c Color) {
	f.DrawText((f.w-TextWidth(s, scale))/2, y, s, scale, c)
}

// Truncate shortens s to fit maxPixels, appending an ellipsis when it cuts.
func Truncate(s string, maxPixels, scale int) string {
	if TextWidth(s, scale) <= maxPixels {
		return s
	}
	runes := []rune(s)
	for len(runes) > 1 {
		runes = runes[:len(runes)-1]
		if TextWidth(string(runes)+"...", scale) <= maxPixels {
			return string(runes) + "..."
		}
	}
	return ""
}
